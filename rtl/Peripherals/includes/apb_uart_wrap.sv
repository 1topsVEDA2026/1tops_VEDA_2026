// =============================================================================
// apb_uart_wrap — Self-contained 16550-compatible UART
// =============================================================================
// Replaces the OBI-dependent PULP version with a standalone implementation.
// APB struct interface → simple 16550 register set.

module apb_uart_wrap #(
    parameter type apb_req_t = logic,
    parameter type apb_rsp_t = logic
)(
    input  logic clk_i,
    input  logic rst_ni,

    // APB (struct-based)
    input  apb_req_t apb_req_i,
    output apb_rsp_t apb_rsp_o,

    // Physical interface
    output logic intr_o,
    output logic out1_no,
    output logic out2_no,
    output logic rts_no,
    output logic dtr_no,
    input  logic cts_ni,
    input  logic dsr_ni,
    input  logic dcd_ni,
    input  logic rin_ni,
    input  logic sin_i,   // RX
    output logic sout_o   // TX
);

    // =========================================================================
    // 16550 Register Offsets (byte-addressed, use bits [4:2] for word access)
    // =========================================================================
    localparam RBR_THR = 3'h0;  // Receive Buffer / Transmit Holding
    localparam IER     = 3'h1;  // Interrupt Enable
    localparam IIR_FCR = 3'h2;  // Interrupt ID / FIFO Control
    localparam LCR     = 3'h3;  // Line Control
    localparam MCR     = 3'h4;  // Modem Control
    localparam LSR     = 3'h5;  // Line Status
    localparam MSR     = 3'h6;  // Modem Status
    localparam SCR     = 3'h7;  // Scratch

    // =========================================================================
    // Registers
    // =========================================================================
    logic [7:0]  reg_thr;       // Transmit Holding
    logic [7:0]  reg_ier;       // Interrupt Enable
    logic [7:0]  reg_lcr;       // Line Control
    logic [7:0]  reg_mcr;       // Modem Control
    logic [7:0]  reg_scr;       // Scratch
    logic [15:0] reg_dll_dlm;   // Divisor Latch

    // FIFOs (simple 16-entry)
    logic [7:0]  rx_fifo [0:15];
    logic [3:0]  rx_wr_ptr, rx_rd_ptr;
    logic [4:0]  rx_count;

    logic [7:0]  tx_fifo [0:15];
    logic [3:0]  tx_wr_ptr, tx_rd_ptr;
    logic [4:0]  tx_count;

    logic        fifo_enabled;

    // TX/RX shift registers
    logic [9:0]  tx_shift;
    logic [3:0]  tx_bit_cnt;
    logic        tx_busy;

    logic [9:0]  rx_shift;
    logic [3:0]  rx_bit_cnt;
    logic        rx_busy;

    // Baud rate
    logic [15:0] baud_counter;
    logic        baud_tick;

    // Status
    logic        tx_empty;
    logic        rx_data_ready;
    logic        overrun_err;

    assign tx_empty      = (tx_count == 0) && !tx_busy;
    assign rx_data_ready = (rx_count != 0);

    // RX done pulse (generated by RX shift register, used by register logic)
    logic rx_done_pulse;

    // =========================================================================
    // APB Read/Write (immediate response)
    // =========================================================================
    logic [2:0]  reg_addr;
    logic        dlab;

    assign reg_addr = apb_req_i.paddr[4:2];
    assign dlab     = reg_lcr[7];

    // APB response: always ready in one cycle
    assign apb_rsp_o.pready  = apb_req_i.psel & apb_req_i.penable;
    assign apb_rsp_o.pslverr = 1'b0;

    // Read data mux
    always_comb begin
        apb_rsp_o.prdata = 32'h0;
        unique case (reg_addr)
            RBR_THR: apb_rsp_o.prdata[7:0] = dlab ? reg_dll_dlm[7:0]  :
                                              (rx_data_ready ? rx_fifo[rx_rd_ptr] : 8'h0);
            IER:     apb_rsp_o.prdata[7:0] = dlab ? reg_dll_dlm[15:8] : reg_ier;
            IIR_FCR: apb_rsp_o.prdata[7:0] = {2'b11, 2'b00, 3'b001, ~(|reg_ier[3:0])};
            LCR:     apb_rsp_o.prdata[7:0] = reg_lcr;
            MCR:     apb_rsp_o.prdata[7:0] = reg_mcr;
            LSR:     apb_rsp_o.prdata[7:0] = {1'b0, tx_empty, tx_empty, 1'b0,
                                               1'b0, 1'b0, overrun_err, rx_data_ready};
            MSR:     apb_rsp_o.prdata[7:0] = {~dcd_ni, ~rin_ni, ~dsr_ni, ~cts_ni,
                                               4'h0};
            SCR:     apb_rsp_o.prdata[7:0] = reg_scr;
            default: apb_rsp_o.prdata = 32'h0;
        endcase
    end

    // =========================================================================
    // Register Write Logic
    // =========================================================================
    logic apb_wr, apb_rd;
    assign apb_wr = apb_req_i.psel & apb_req_i.penable & apb_req_i.pwrite;
    assign apb_rd = apb_req_i.psel & apb_req_i.penable & ~apb_req_i.pwrite;

    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            reg_thr     <= 8'h0;
            reg_ier     <= 8'h0;
            reg_lcr     <= 8'h03;  // 8N1 default
            reg_mcr     <= 8'h0;
            reg_scr     <= 8'h0;
            reg_dll_dlm <= 16'h0001;
            fifo_enabled <= 1'b0;
            tx_wr_ptr   <= 4'h0;
            tx_rd_ptr   <= 4'h0;
            tx_count    <= 5'h0;
            rx_wr_ptr   <= 4'h0;
            rx_rd_ptr   <= 4'h0;
            rx_count    <= 5'h0;
            overrun_err <= 1'b0;
        end else begin
            // Read side-effects: pop RX FIFO
            if (apb_rd && reg_addr == RBR_THR && !dlab && rx_data_ready) begin
                rx_rd_ptr <= rx_rd_ptr + 1;
                rx_count  <= rx_count - 1;
                overrun_err <= 1'b0;
            end

            // Write
            if (apb_wr) begin
                unique case (reg_addr)
                    RBR_THR: begin
                        if (dlab) begin
                            reg_dll_dlm[7:0] <= apb_req_i.pwdata[7:0];
                        end else if (tx_count < 16) begin
                            tx_fifo[tx_wr_ptr] <= apb_req_i.pwdata[7:0];
                            tx_wr_ptr <= tx_wr_ptr + 1;
                            tx_count  <= tx_count + 1;
                        end
                    end
                    IER: begin
                        if (dlab)
                            reg_dll_dlm[15:8] <= apb_req_i.pwdata[7:0];
                        else
                            reg_ier <= apb_req_i.pwdata[7:0];
                    end
                    IIR_FCR: begin
                        fifo_enabled <= apb_req_i.pwdata[0];
                        if (apb_req_i.pwdata[1]) begin // RX FIFO reset
                            rx_wr_ptr <= 4'h0;
                            rx_rd_ptr <= 4'h0;
                            rx_count  <= 5'h0;
                        end
                        if (apb_req_i.pwdata[2]) begin // TX FIFO reset
                            tx_wr_ptr <= 4'h0;
                            tx_rd_ptr <= 4'h0;
                            tx_count  <= 5'h0;
                        end
                    end
                    LCR: reg_lcr <= apb_req_i.pwdata[7:0];
                    MCR: reg_mcr <= apb_req_i.pwdata[7:0];
                    SCR: reg_scr <= apb_req_i.pwdata[7:0];
                    default: ;
                endcase
            end

            // TX: pop from FIFO when shift register is free
            if (!tx_busy && tx_count > 0) begin
                tx_rd_ptr <= tx_rd_ptr + 1;
                tx_count  <= tx_count - 1;
            end

            // RX: push received byte
            if (rx_done_pulse) begin
                if (rx_count < 16) begin
                    rx_fifo[rx_wr_ptr] <= rx_shift[8:1];
                    rx_wr_ptr <= rx_wr_ptr + 1;
                    rx_count  <= rx_count + 1;
                end else begin
                    overrun_err <= 1'b1;
                end
            end
        end
    end

    // =========================================================================
    // Baud Rate Generator
    // =========================================================================
    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            baud_counter <= 16'h0;
            baud_tick    <= 1'b0;
        end else begin
            if (baud_counter >= (reg_dll_dlm << 4) - 1) begin
                baud_counter <= 16'h0;
                baud_tick    <= 1'b1;
            end else begin
                baud_counter <= baud_counter + 1;
                baud_tick    <= 1'b0;
            end
        end
    end

    // =========================================================================
    // TX Shift Register
    // =========================================================================
    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            tx_shift   <= 10'h3FF;
            tx_bit_cnt <= 4'h0;
            tx_busy    <= 1'b0;
        end else begin
            if (!tx_busy && tx_count > 0) begin
                // Load shift register: start(0) + data(8) + stop(1)
                tx_shift   <= {1'b1, tx_fifo[tx_rd_ptr], 1'b0};
                tx_bit_cnt <= 4'd10;
                tx_busy    <= 1'b1;
            end else if (tx_busy && baud_tick) begin
                tx_shift   <= {1'b1, tx_shift[9:1]};
                tx_bit_cnt <= tx_bit_cnt - 1;
                if (tx_bit_cnt == 1)
                    tx_busy <= 1'b0;
            end
        end
    end

    assign sout_o = tx_busy ? tx_shift[0] : 1'b1;

    // =========================================================================
    // RX Shift Register
    // =========================================================================
    logic sin_q, sin_qq;

    // Synchronizer
    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            sin_q  <= 1'b1;
            sin_qq <= 1'b1;
        end else begin
            sin_q  <= sin_i;
            sin_qq <= sin_q;
        end
    end

    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            rx_shift      <= 10'h0;
            rx_bit_cnt    <= 4'h0;
            rx_busy       <= 1'b0;
            rx_done_pulse <= 1'b0;
        end else begin
            rx_done_pulse <= 1'b0;
            if (!rx_busy) begin
                // Detect start bit (falling edge)
                if (!sin_qq) begin
                    rx_busy    <= 1'b1;
                    rx_bit_cnt <= 4'd10;
                end
            end else if (baud_tick) begin
                rx_shift   <= {sin_qq, rx_shift[9:1]};
                rx_bit_cnt <= rx_bit_cnt - 1;
                if (rx_bit_cnt == 1) begin
                    rx_busy       <= 1'b0;
                    rx_done_pulse <= 1'b1;
                end
            end
        end
    end

    // =========================================================================
    // Modem Control Outputs
    // =========================================================================
    assign rts_no  = ~reg_mcr[1];
    assign dtr_no  = ~reg_mcr[0];
    assign out1_no = ~reg_mcr[2];
    assign out2_no = ~reg_mcr[3];

    // =========================================================================
    // Interrupt
    // =========================================================================
    logic irq_rx, irq_tx, irq_modem;
    assign irq_rx    = reg_ier[0] & rx_data_ready;
    assign irq_tx    = reg_ier[1] & tx_empty;
    assign irq_modem = reg_ier[3] & (~dcd_ni | ~rin_ni | ~dsr_ni | ~cts_ni);
    assign intr_o    = irq_rx | irq_tx | irq_modem;

endmodule : apb_uart_wrap
